"""
================================================================================
[10] 동적 계획법 (Dynamic Programming, DP)
================================================================================

## 개념
큰 문제를 작은 부분 문제로 나누고, 부분 문제의 결과를 저장해두어
같은 계산을 반복하지 않는 방법이에요.
재귀 + 메모이제이션, 또는 바텀업(bottom-up) 방식으로 구현해요.

## DP를 쓸 수 있는 조건 (두 가지 다 만족해야 해요)
  1. 최적 부분 구조 (Optimal Substructure)
     : 큰 문제의 최적해가 작은 문제의 최적해로 구성된다.
  2. 중복 부분 문제 (Overlapping Subproblems)
     : 같은 작은 문제가 여러 번 반복된다.

## 두 가지 구현 방법
  [방법 1] 탑다운 (Top-Down) = 재귀 + 메모이제이션
    - 큰 문제에서 시작해 아래로 내려가며 결과를 저장
    - memo = {}  →  계산 전 memo에 있으면 바로 반환

  [방법 2] 바텀업 (Bottom-Up) = 반복문
    - 가장 작은 문제부터 시작해 위로 올라가며 결과를 저장
    - dp 테이블을 순서대로 채워나감

## 공식
  점화식 (Recurrence Relation): dp[i] = f(dp[i-1], dp[i-2], ...)
  예시: 피보나치  dp[n] = dp[n-1] + dp[n-2]

================================================================================
"""


# ===== 개념 코드: 피보나치로 탑다운 vs 바텀업 비교 =====

# 방법 1: 탑다운 (재귀 + 메모이제이션)
def fib_topdown(n, memo={}):
    if n <= 1:
        return n
    if n in memo:         # 이미 계산했으면 재사용
        return memo[n]
    memo[n] = fib_topdown(n - 1, memo) + fib_topdown(n - 2, memo)
    return memo[n]


# 방법 2: 바텀업 (반복문으로 작은 것부터 채우기)
def fib_bottomup(n):
    if n <= 1:
        return n
    dp = [0] * (n + 1)
    dp[0] = 0
    dp[1] = 1
    for i in range(2, n + 1):
        dp[i] = dp[i - 1] + dp[i - 2]   # 점화식
    return dp[n]


# ================================================================================
# 예제 문제
# ================================================================================
# 문제: 계단 오르기
#       n개의 계단이 있고, 한 번에 1칸 또는 2칸 오를 수 있어요.
#       n번째 계단에 오르는 방법의 수를 구하세요.
#
# 입력: 정수 n (계단의 수)
# 출력: 오르는 방법의 수
#
# 예시:
#   n=1: {1칸}                        → 1가지
#   n=2: {1+1칸, 2칸}                 → 2가지
#   n=3: {1+1+1, 1+2, 2+1}           → 3가지
#   n=4: {1+1+1+1, 1+1+2, 1+2+1,    → 5가지
#          2+1+1, 2+2}
#   n=5:                              → 8가지
#
# 힌트: 마지막 한 칸으로 왔다면 → n-1번째에서, 마지막 두 칸으로 왔다면 → n-2번째에서
#        dp[n] = dp[n-1] + dp[n-2]  (피보나치와 같은 구조!)
# ================================================================================

def climb_stairs(n):
    if n <= 0:
        return 0
    if n == 1:
        return 1
    if n == 2:
        return 2

    dp = [0] * (n + 1)
    dp[1] = 1   # 1칸 계단: 1가지 방법
    dp[2] = 2   # 2칸 계단: 2가지 방법
    for i in range(3, n + 1):
        dp[i] = dp[i - 1] + dp[i - 2]   # 점화식

    return dp[n]


if __name__ == "__main__":
    print("=== 탑다운 vs 바텀업 피보나치 비교 ===")
    for i in range(10):
        print(f"  fib({i}) = {fib_topdown(i)}  (바텀업: {fib_bottomup(i)})")

    print()
    print("=== 예제 문제: 계단 오르기 ===")
    for n in range(1, 11):
        ways = climb_stairs(n)
        print(f"  {n}칸 계단: {ways}가지 방법")

    print()
    print("=== 계단 오르기 dp 테이블 시각화 ===")
    n = 7
    dp = [0] * (n + 1)
    dp[1] = 1
    dp[2] = 2
    for i in range(3, n + 1):
        dp[i] = dp[i - 1] + dp[i - 2]
    print(f"  dp = {dp[1:]}")
    print(f"  (피보나치 수열: 1, 2, 3, 5, 8, 13, 21, ...)")
