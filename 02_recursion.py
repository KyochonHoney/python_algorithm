"""
================================================================================
[02] 재귀 (Recursion)
================================================================================

## 개념
함수가 자기 자신을 호출하여 문제를 더 작은 단위로 나눠 푸는 방법이에요.
마치 "문제를 작게 쪼개서 같은 방법으로 다시 풀기"라고 생각하면 돼요.

## 재귀 함수의 2가지 필수 요소
  1. 기저 조건 (Base Case)  : 재귀를 멈추는 조건 (없으면 무한 루프!)
  2. 재귀 호출 (Recursive Call) : 문제를 더 작게 만들어 자기 자신 호출

## 공식 (재귀의 일반적인 구조)
  def f(n):
      if n == 기저조건:      # ① 기저 조건
          return 기저값
      return f(n-1) + ...   # ② 재귀 호출 (n이 점점 작아짐)

## 시간복잡도
  T(n) = T(n-1) + O(1)  →  O(n)

================================================================================
"""


# ===== 개념 코드: 팩토리얼 =====
# n! = n × (n-1) × (n-2) × ... × 2 × 1
# 재귀로 표현: n! = n × (n-1)!

def factorial(n):
    if n == 0 or n == 1:   # 기저 조건: 0! = 1, 1! = 1
        return 1
    return n * factorial(n - 1)   # 재귀 호출

# 호출 흐름 예시:
# factorial(4)
#   → 4 × factorial(3)
#       → 3 × factorial(2)
#           → 2 × factorial(1)
#               → 1   (기저 조건)
#           ← 2 × 1 = 2
#       ← 3 × 2 = 6
#   ← 4 × 6 = 24


# ================================================================================
# 예제 문제
# ================================================================================
# 문제: 자연수 n이 주어졌을 때, 1부터 n까지 숫자를 더한 합을 재귀로 구하세요.
#
# 입력: 정수 n (n >= 1)
# 출력: 1 + 2 + ... + n 의 합
#
# 예시:
#   n = 5  →  1+2+3+4+5 = 15
#   n = 10 →  1+2+...+10 = 55
#
# 힌트: sum(n) = n + sum(n-1)
#       기저조건은 n == 1 일 때 1을 반환
# ================================================================================

def sum_recursive(n):
    # ✏️ 여기에 코드를 작성해보세요!
    # 기저 조건 (Base Case)
    if n == 1:
        return 1
    # 재귀 호출 (Recursive Call)
    return n + sum_recursive(n - 1)


if __name__ == "__main__":
    # 팩토리얼 확인
    print("=== 팩토리얼 ===")
    for i in range(6):
        print(f"  {i}! = {factorial(i)}")

    print()
    print("=== 예제 문제: 1부터 n까지의 합 ===")
    test_cases = [1, 5, 10, 100]
    for n in test_cases:
        result = sum_recursive(n)
        answer = n * (n + 1) // 2   # 수학 공식으로 검증
        ok = "OK" if result == answer else "XX"
        print(f"  sum(1~{n:3d}) = {result:6d}  (검증: {answer})  [{ok}]")
