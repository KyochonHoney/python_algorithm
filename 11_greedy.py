# 예제 문제
# ================================================================================
# 문제: 회의실 배정
#       여러 회의가 시작 시간과 종료 시간을 가지고 있어요.
#       하나의 회의실을 최대한 많이 사용하려면 어떤 회의들을 선택해야 할까요?
#
# 입력: [(시작시간, 종료시간), ...] 형태의 회의 목록
# 출력: 선택한 회의 목록, 최대 회의 수
#
# 예시:
#   [(1,4), (3,5), (0,6), (5,7), (3,8), (5,9), (6,10), (8,11), (8,12), (2,13), (12,14)]
#   결과: 최대 4개의 회의 선택 가능
#
# 핵심 그리디 선택: "종료 시간이 가장 빠른 회의를 먼저 선택한다"
#   → 종료가 빠를수록 다음 회의를 위한 시간을 더 많이 남길 수 있기 때문!
# ================================================================================

def select_meetings(meetings):
    # 종료 시간 기준 오름차순 정렬 (종료 시간이 같으면 시작 시간 기준)
    sorted_meetings = sorted(meetings, key=lambda x: (x[1], x[0]))

    selected = []
    last_end = 0   # 마지막으로 선택한 회의의 종료 시간

    for start, end in sorted_meetings:
        if start >= last_end:   # 이전 회의가 끝난 후 시작하는 회의만 선택
            selected.append((start, end))
            last_end = end

    return selected


if __name__ == "__main__":
    print("=== 그리디: 동전 거스름돈 ===")
    coins = [500, 100, 50, 10]
    for amount in [1260, 730, 1000, 4680]:
        count, breakdown = min_coins_greedy(amount, coins)
        detail = ", ".join(f"{coin}원×{num}" for coin, num in breakdown.items())
        print(f"  {amount}원 →  {count}개  ({detail})")

    print()
    print("=== 예제 문제: 회의실 배정 ===")
    meetings = [(1,4), (3,5), (0,6), (5,7), (3,8), (5,9), (6,10), (8,11), (8,12), (2,13), (12,14)]
    print(f"  회의 목록 (시작, 종료): {meetings}")
    selected = select_meetings(meetings)
    print(f"  선택된 회의 {len(selected)}개: {selected}")
    print()
    print("  [시각화]  (=: 선택된 회의 시간)")
    for s, e in selected:
        bar = " " * s + "=" * (e - s)
        print(f"  {s:2d}~{e:2d} |{bar}|")
